// CSV / JSON export helpers (browser-side downloads).

export function toCSV(headers: string[], rows: (string | number)[][]): string {
  const escape = (v: string | number) => {
    const s = String(v);
    return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
  };
  return [headers.map(escape).join(","), ...rows.map((r) => r.map(escape).join(","))].join("\n");
}

export function downloadFile(filename: string, content: string, mime: string) {
  const blob = new Blob([content], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

export function downloadCSV(filename: string, headers: string[], rows: (string | number)[][]) {
  downloadFile(filename, toCSV(headers, rows), "text/csv;charset=utf-8");
}

export function downloadJSON(filename: string, data: unknown) {
  downloadFile(filename, JSON.stringify(data, null, 2), "application/json");
}

/** Print-friendly report: opens a styled HTML report in a new window for Save-as-PDF. */
export function printReport(title: string, bodyHtml: string) {
  const win = window.open("", "_blank");
  if (!win) return;
  win.document.write(`<!doctype html><html><head><title>${title}</title><style>
    body{font-family:ui-monospace,Menlo,monospace;margin:40px;color:#111}
    h1{font-size:22px} h2{font-size:16px;margin-top:24px}
    table{border-collapse:collapse;width:100%;margin-top:8px}
    th,td{border:1px solid #999;padding:6px 10px;text-align:left;font-size:12px}
    th{background:#eee}
    .meta{color:#555;font-size:12px}
  </style></head><body><h1>${title}</h1><p class="meta">Generated by OSense 2.0 — ${new Date().toLocaleString()}</p>${bodyHtml}</body></html>`);
  win.document.close();
  win.focus();
  win.print();
}
